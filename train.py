#!/usr/bin/env python3
"""
RF-DETR Training Script
=======================
Тренування RF-DETR моделей детекції об'єктів з YOLO-style аугментаціями.
Усі параметри конфігурації знаходяться на початку файлу.

Usage:
    python train.py

Налаштуйте конфігурацію нижче перед запуском.
"""

import multiprocessing
from pathlib import Path

from rfdetr.training import (
    setup_seed,
    AugmentationConfig,
    TrainingConfig,
    ModelConfig,
    RFDETRTrainer,
)


# =============================================================================
# БАЗОВА КОНФІГУРАЦІЯ
# =============================================================================
SEED = 42
PROJECT_NAME = "rfdetr_training"

# Шляхи
BASE_DIR = Path(__file__).parent
DATASET_DIR = BASE_DIR / "tests" / "test_dataset"  # Змініть на ваш датасет

# Модель
PRETRAINED_WEIGHTS = None  # Шлях до ваг або None для завантаження з HuggingFace


# =============================================================================
# КОНФІГУРАЦІЯ МОДЕЛІ
# =============================================================================
MODEL_CONFIG = ModelConfig(
    model_size="n",                 # Розмір моделі: n=nano, s=small, m=medium, b=base, l=large
    num_classes=3,                  # Кількість класів (автовизначається з датасету)
    pretrained_weights=PRETRAINED_WEIGHTS,  # Шлях до попередньо навчених ваг
    freeze_encoder=False,           # Заморозити encoder (DINOv2 backbone)
    freeze_encoder_epochs=0,        # Кількість епох з замороженим encoder (0 = не заморожувати)
)


# =============================================================================
# КОНФІГУРАЦІЯ ТРЕНУВАННЯ
# =============================================================================
TRAINING_CONFIG = TrainingConfig(
    # -------------------------------------------------------------------------
    # Налаштування проекту
    # -------------------------------------------------------------------------
    project=f"runs/{PROJECT_NAME}",  # Папка для збереження результатів
    name="exp",                      # Назва run: створює exp, exp2, exp3, ...
    exist_ok=False,                  # True = перезаписати існуючий run
    
    # -------------------------------------------------------------------------
    # Основні параметри навчання
    # -------------------------------------------------------------------------
    epochs=10,                       # Кількість епох тренування
    batch_size=8,                    # Розмір батчу (зменшіть якщо мало GPU пам'яті)
    
    # -------------------------------------------------------------------------
    # Оптимізатор (AdamW)
    # -------------------------------------------------------------------------
    lr=1e-4,                         # Learning rate (рекомендовано: 1e-4 для fine-tuning)
    weight_decay=1e-4,               # L2 регуляризація (рекомендовано: 1e-4)
    
    # -------------------------------------------------------------------------
    # Learning rate scheduler
    # -------------------------------------------------------------------------
    scheduler="cosine",              # Тип scheduler: "cosine", "step", "linear"
    warmup_epochs=3,                 # Кількість warmup епох (поступове збільшення LR)
    
    # -------------------------------------------------------------------------
    # Градієнти
    # -------------------------------------------------------------------------
    gradient_accumulation=1,         # Накопичення градієнтів (ефективний batch = batch_size * accumulation)
    grad_clip=0.1,                   # Максимальна норма градієнта (0 = вимкнено)
    
    # -------------------------------------------------------------------------
    # Валідація та збереження
    # -------------------------------------------------------------------------
    val_period=1,                    # Валідація кожні N епох
    save_period=-1,                  # Збереження checkpoint кожні N епох (-1 = тільки best/last)
    early_stopping=50,               # Зупинка якщо метрика не покращується N епох (0 = вимкнено)
    
    # -------------------------------------------------------------------------
    # Візуалізації
    # -------------------------------------------------------------------------
    vis_batches=10,                   # Кількість батчів для візуалізації (train/val)
    
    # -------------------------------------------------------------------------
    # Device та workers
    # -------------------------------------------------------------------------
    device="cuda",                   # Пристрій: "cuda" або "cpu"
    workers=8,                       # DataLoader workers (0 для Windows сумісності)
)


# =============================================================================
# КОНФІГУРАЦІЯ АУГМЕНТАЦІЙ (ULTRALYTICS-STYLE)
# =============================================================================
AUGMENTATION_CONFIG = AugmentationConfig(
    # -------------------------------------------------------------------------
    # ПРИМІТКА: Розмір зображення (imgsz) автоматично береться з моделі:
    # Nano=384, Small=512, Medium=576, Base=560, Large=560
    # -------------------------------------------------------------------------
    
    # -------------------------------------------------------------------------
    # HSV аугментації (Hue, Saturation, Value)
    # Змінюють колір зображення для кращої генералізації
    # -------------------------------------------------------------------------
    hsv_h=0.0,                     # Hue gain (0-1): зміна відтінку
    hsv_s=0.0,                       # Saturation gain (0-1): зміна насиченості
    hsv_v=0.4,                       # Value gain (0-1): зміна яскравості
    
    # -------------------------------------------------------------------------
    # Додаткові колірні аугментації
    # -------------------------------------------------------------------------
    brightness=0.2,                  # Ймовірність зміни яскравості (0-1)
    contrast=0.2,                    # Ймовірність зміни контрасту (0-1)
    blur=0.1,                        # Ймовірність Gaussian blur (0-1)
    noise=0.2,                       # Ймовірність Gaussian noise (0-1)
    
    # -------------------------------------------------------------------------
    # Геометричні трансформації (RandomPerspective)
    # -------------------------------------------------------------------------
    degrees=10.0,                     # Максимальний поворот (+/- degrees)
    translate=0.1,                   # Максимальний зсув (fraction від розміру)
    scale=0.5,                       # Масштаб (+/- scale, напр. 0.5 = від 0.5x до 1.5x)
    shear=0.0,                       # Зсув перспективи (degrees)
    perspective=0.0,                 # Перспективна деформація (0-0.001)
    
    # -------------------------------------------------------------------------
    # Відзеркалення (Flip)
    # -------------------------------------------------------------------------
    fliplr=0.5,                      # Ймовірність горизонтального flip
    flipud=0.0,                      # Ймовірність вертикального flip
    
    # -------------------------------------------------------------------------
    # Композитні аугментації (об'єднання кількох зображень)
    # -------------------------------------------------------------------------
    mosaic=1.0,                      # Ймовірність Mosaic (4 зображення в одне)
    mixup=0.0,                       # Ймовірність MixUp (альфа-блендинг 2 зображень)
    cutmix=0.0,                      # Ймовірність CutMix (вирізання регіонів)
    close_mosaic=5,                 # Вимкнути Mosaic в останніх N епохах
    
    # -------------------------------------------------------------------------
    # Random Erasing (видалення випадкових регіонів)
    # Box-aware: не видаляє занадто багато від об'єктів
    # -------------------------------------------------------------------------
    erasing=0.25,                     # Ймовірність Random Erasing (0-1)
    erasing_min_visible=0.5,          # Мін. видима частина боксу (0.5 = 50% має залишитись)
    erasing_min_box_size=20,          # Мін. розмір боксу після erasing (пікселі)
)


# =============================================================================
# ГОЛОВНА ФУНКЦІЯ
# =============================================================================

def main():
    """Головна функція для запуску тренування."""
    # Налаштування seed для відтворюваності
    setup_seed(SEED)
    
    # Визначаємо resolution по розміру моделі
    model_resolutions = {'n': 384, 's': 512, 'm': 576, 'b': 560, 'l': 560}
    resolution = model_resolutions.get(MODEL_CONFIG.model_size, 560)
    
    print("\n" + "=" * 70)
    print("RF-DETR TRAINING")
    print("=" * 70)
    print(f"Seed: {SEED}")
    print(f"Dataset: {DATASET_DIR}")
    print(f"Model size: {MODEL_CONFIG.model_size}")
    print(f"Image size: {resolution} (auto)")
    print(f"Epochs: {TRAINING_CONFIG.epochs}")
    print(f"Batch size: {TRAINING_CONFIG.batch_size}")
    print("=" * 70 + "\n")
    
    # Перевірка датасету
    if not DATASET_DIR.exists():
        print(f"❌ ПОМИЛКА: Датасет не знайдено: {DATASET_DIR}")
        print("Будь ласка, вкажіть правильний шлях у змінній DATASET_DIR")
        return None
    
    # Створюємо trainer
    trainer = RFDETRTrainer(
        model_config=MODEL_CONFIG,
        training_config=TRAINING_CONFIG,
        augmentation_config=AUGMENTATION_CONFIG,
        seed=SEED,
    )
    
    # Запуск тренування
    results = trainer.train(dataset_dir=str(DATASET_DIR))
    
    # Виведення результатів
    print("\n" + "=" * 70)
    print("[OK] ТРЕНУВАННЯ ЗАВЕРШЕНО")
    print("=" * 70)
    print(f"Результати збережено: {results['save_dir']}")
    print(f"Best mAP: {results['best_map']:.4f}")
    print(f"Epochs trained: {results['epochs_trained']}")
    print("=" * 70 + "\n")
    
    return results


def resume_training(checkpoint_path: str):
    """
    Продовження тренування з checkpoint.
    
    Args:
        checkpoint_path: Шлях до checkpoint файлу
    """
    setup_seed(SEED)
    
    trainer = RFDETRTrainer(
        model_config=MODEL_CONFIG,
        training_config=TRAINING_CONFIG,
        augmentation_config=AUGMENTATION_CONFIG,
        seed=SEED,
    )
    
    print(f"\n[Resume] Продовження тренування з: {checkpoint_path}\n")
    results = trainer.train(dataset_dir=str(DATASET_DIR), resume=checkpoint_path)
    
    return results


if __name__ == "__main__":
    # Windows multiprocessing fix (дозволяє використовувати workers > 0)
    multiprocessing.freeze_support()
    
    # Режим 1: Базове тренування
    main()
    
